def repo_paths():
    experiments_dir = Path(__file__).resolve().parents[2]
    return experiments_dir, experiments_dir / "logs", experiments_dir / "figures"


def parse_args():
    experiments_dir, logs_dir, figures_dir = repo_paths()
    parser = argparse.ArgumentParser(
        description="Analyze CSV logs generated by autotrans_logger."
    )
    parser.add_argument(
        "--csv",
        dest="csv_path",
        default=None,
        help="Path to autotrans_logger CSV file.",
    )
    parser.add_argument(
        "--output_dir",
        default=str(figures_dir),
        help="Directory for metrics_summary.txt and PNG plots.",
    )
    parser.set_defaults(default_logs_dir=str(logs_dir), experiments_dir=str(experiments_dir))
    return parser.parse_args()


def find_latest_csv(logs_dir):
    candidates = glob.glob(os.path.join(logs_dir, "autotrans_log_*.csv"))
    if not candidates:
        raise FileNotFoundError(
            "No CSV was provided and no autotrans_log_*.csv file exists in %s" % logs_dir
        )
    return max(candidates, key=os.path.getmtime)


def parse_float(value):
    if value is None:
        return math.nan
    value = str(value).strip()
    if value == "":
        return math.nan
    try:
        return float(value)
    except ValueError:
        return math.nan


def read_csv_rows(csv_path):
    if not os.path.exists(csv_path):
        raise FileNotFoundError("CSV file does not exist: %s" % csv_path)
    if os.path.getsize(csv_path) == 0:
        raise ValueError("CSV file is empty: %s" % csv_path)

    with open(csv_path, "r", newline="") as csv_file:
        reader = csv.DictReader(csv_file)
        if not reader.fieldnames:
            raise ValueError("CSV file has no header: %s" % csv_path)
        rows = list(reader)

    if not rows:
        raise ValueError("CSV file has no data rows: %s" % csv_path)

    missing_columns = [name for name in NUMERIC_COLUMNS if name not in reader.fieldnames]
    if missing_columns:
        print(
            "WARNING: missing columns: %s" % ", ".join(missing_columns),
            file=sys.stderr,
        )

    return rows, reader.fieldnames


def column(rows, name):
    return [parse_float(row.get(name)) for row in rows]


def valid_values(values):
    return [value for value in values if math.isfinite(value)]


def mean(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return sum(values) / len(values)


def percentile(values, percent):
    values = sorted(valid_values(values))
    if not values:
        return math.nan
    if len(values) == 1:
        return values[0]
    rank = (len(values) - 1) * percent / 100.0
    low_index = int(math.floor(rank))
    high_index = int(math.ceil(rank))
    if low_index == high_index:
        return values[low_index]
    weight = rank - low_index
    return values[low_index] * (1.0 - weight) + values[high_index] * weight


def max_or_nan(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return max(values)


def has_column(rows, name):
    return bool(rows) and name in rows[0]


def vector_norm_triplets(xs, ys, zs):
    norms = []
    for x_value, y_value, z_value in zip(xs, ys, zs):
        if all(math.isfinite(value) for value in (x_value, y_value, z_value)):
            norms.append(math.sqrt(x_value * x_value + y_value * y_value + z_value * z_value))
        else:
            norms.append(math.nan)
    return norms


def path_length(xs, ys, zs):
    total = 0.0
    previous = None
    for point in zip(xs, ys, zs):
        if not all(math.isfinite(value) for value in point):
            continue
        if previous is not None:
            total += math.sqrt(sum((point[i] - previous[i]) ** 2 for i in range(3)))
        previous = point
    return total if previous is not None else math.nan


def final_position(xs, ys, zs):
    for point in reversed(list(zip(xs, ys, zs))):
        if all(math.isfinite(value) for value in point):
            return point
    return None


def compute_duration_and_rate(rows):
    ros_time = valid_values(column(rows, "ros_time"))
    wall_time = valid_values(column(rows, "wall_time"))
    times = ros_time if len(ros_time) >= 2 else wall_time
    if len(times) < 2:
        return math.nan, math.nan
    duration = times[-1] - times[0]
    if duration <= 0.0:
        return math.nan, math.nan
    return duration, (len(rows) - 1) / duration


def compute_metrics(csv_path, rows):
    uav_pos_x = column(rows, "uav_pos_x")
    uav_pos_y = column(rows, "uav_pos_y")
    uav_pos_z = column(rows, "uav_pos_z")
    uav_vel_x = column(rows, "uav_vel_x")
    uav_vel_y = column(rows, "uav_vel_y")
    uav_vel_z = column(rows, "uav_vel_z")

    payload_pos_x = column(rows, "payload_pos_x")
    payload_pos_y = column(rows, "payload_pos_y")
    payload_pos_z = column(rows, "payload_pos_z")
    payload_vel_x = column(rows, "payload_vel_x")
    payload_vel_y = column(rows, "payload_vel_y")
    payload_vel_z = column(rows, "payload_vel_z")

    uav_speed = vector_norm_triplets(uav_vel_x, uav_vel_y, uav_vel_z)
    payload_speed = vector_norm_triplets(payload_vel_x, payload_vel_y, payload_vel_z)
    swing_angle = column(rows, "swing_angle_deg")
    has_trajectory = column(rows, "has_trajectory")
    valid_has_trajectory = valid_values(has_trajectory)
    wind_force_norm = column(rows, "wind_force_norm") if has_column(rows, "wind_force_norm") else []

    duration_sec, effective_log_rate_hz = compute_duration_and_rate(rows)
    final_uav_position = final_position(uav_pos_x, uav_pos_y, uav_pos_z)
    final_payload_position = final_position(payload_pos_x, payload_pos_y, payload_pos_z)

    if valid_has_trajectory and max(valid_has_trajectory) <= 0.0:
        print("WARNING: no valid trajectory data detected in has_trajectory.", file=sys.stderr)
    elif not valid_has_trajectory:
        print("WARNING: has_trajectory has no valid numeric data.", file=sys.stderr)

    metrics = {
        "csv_path": os.path.abspath(csv_path),
        "sample_count": len(rows),
        "duration_sec": duration_sec,
        "effective_log_rate_hz": effective_log_rate_hz,
        "has_trajectory_ratio": mean([1.0 if value > 0.5 else 0.0 for value in valid_has_trajectory]),
        "mean_swing_angle_deg": mean(swing_angle),
        "max_swing_angle_deg": max_or_nan(swing_angle),
        "p95_swing_angle_deg": percentile(swing_angle, 95.0),
        "max_uav_speed": max_or_nan(uav_speed),
        "mean_uav_speed": mean(uav_speed),
        "max_payload_speed": max_or_nan(payload_speed),
        "mean_payload_speed": mean(payload_speed),
        "uav_path_length": path_length(uav_pos_x, uav_pos_y, uav_pos_z),
        "payload_path_length": path_length(payload_pos_x, payload_pos_y, payload_pos_z),
        "final_uav_position": final_uav_position,
        "final_payload_position": final_payload_position,
    }

    if wind_force_norm:
        metrics["mean_wind_force_norm"] = mean(wind_force_norm)
        metrics["max_wind_force_norm"] = max_or_nan(wind_force_norm)

    return metrics


def format_value(value):
    if value is None:
        return "nan"
    if isinstance(value, tuple):
        return "(%.6f, %.6f, %.6f)" % value
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if math.isfinite(value):
            return "%.6f" % value
        return "nan"
    return str(value)


def write_metrics(output_dir, metrics):
    os.makedirs(output_dir, exist_ok=True)
    lines = ["%s: %s" % (key, format_value(value)) for key, value in metrics.items()]
    text = "\n".join(lines) + "\n"
    print(text, end="")
    summary_path = os.path.join(output_dir, "metrics_summary.txt")
    with open(summary_path, "w") as summary_file:
        summary_file.write(text)
    print("metrics_summary_path: %s" % os.path.abspath(summary_path))


def relative_time(rows):
    times = column(rows, "ros_time")
    valid_times = valid_values(times)
    if not valid_times:
        return [math.nan for _ in rows]
    start_time = valid_times[0]
    return [value - start_time if math.isfinite(value) else math.nan for value in times]


def finite_xy(xs, ys):
    out_x = []
    out_y = []
    for x_value, y_value in zip(xs, ys):
        if math.isfinite(x_value) and math.isfinite(y_value):
            out_x.append(x_value)
            out_y.append(y_value)
    return out_x, out_y


def plot_or_warn(output_dir, filename, plot_func):
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("WARNING: matplotlib is not available; plots were not generated.", file=sys.stderr)
        return False

    path = os.path.join(output_dir, filename)
    try:
        fig = plt.figure()
        plot_func(plt)
        fig.tight_layout()
        fig.savefig(path, dpi=150)
        plt.close(fig)
        return True
    except Exception as exc:
        plt.close("all")
        print("WARNING: failed to generate %s: %s" % (filename, exc), file=sys.stderr)
        return False


def plot_time_series(plt, time_sec, series, ylabel, title):
    plotted = False
    for label, values in series:
        xs = []
        ys = []
        for time_value, value in zip(time_sec, values):
            if math.isfinite(time_value) and math.isfinite(value):
                xs.append(time_value)
                ys.append(value)
        if xs:
            plt.plot(xs, ys, label=label)
            plotted = True
    if not plotted:
        raise ValueError("no finite data")
    plt.xlabel("time [s]")
    plt.ylabel(ylabel)
    plt.title(title)
    plt.grid(True)
    if len(series) > 1:
        plt.legend()


def make_plots(rows, output_dir):
    os.makedirs(output_dir, exist_ok=True)
    time_sec = relative_time(rows)

    uav_speed = vector_norm_triplets(
        column(rows, "uav_vel_x"), column(rows, "uav_vel_y"), column(rows, "uav_vel_z")
    )
    payload_speed = vector_norm_triplets(
        column(rows, "payload_vel_x"),
        column(rows, "payload_vel_y"),
        column(rows, "payload_vel_z"),
    )

    plot_or_warn(
        output_dir,
        "swing_angle.png",
        lambda plt: plot_time_series(
            plt,
            time_sec,
            [("swing_angle_deg", column(rows, "swing_angle_deg"))],
            "angle [deg]",
            "Payload swing angle",
        ),
    )

    def plot_xy(plt):
        uav_x, uav_y = finite_xy(column(rows, "uav_pos_x"), column(rows, "uav_pos_y"))
        payload_x, payload_y = finite_xy(column(rows, "payload_pos_x"), column(rows, "payload_pos_y"))
        if not uav_x and not payload_x:
            raise ValueError("no finite XY trajectory data")
        if uav_x:
            plt.plot(uav_x, uav_y, label="uav")
        if payload_x:
            plt.plot(payload_x, payload_y, label="payload")
        plt.xlabel("x [m]")
        plt.ylabel("y [m]")
        plt.title("XY trajectory")
        plt.axis("equal")
        plt.grid(True)
        plt.legend()

    plot_or_warn(output_dir, "xy_trajectory.png", plot_xy)

    plot_or_warn(
        output_dir,
        "altitude.png",
        lambda plt: plot_time_series(
            plt,
            time_sec,
            [
                ("uav_z", column(rows, "uav_pos_z")),
                ("payload_z", column(rows, "payload_pos_z")),
            ],
            "z [m]",
            "Altitude",
        ),
    )

    plot_or_warn(
        output_dir,
        "speed.png",
        lambda plt: plot_time_series(
            plt,
            time_sec,
            [("uav_speed", uav_speed), ("payload_speed", payload_speed)],
            "speed [m/s]",
            "Speed",
        ),
    )

    plot_or_warn(
        output_dir,
        "thrust_bodyrate.png",
        lambda plt: plot_time_series(
            plt,
            time_sec,
            [
                ("so3_thrust", column(rows, "so3_thrust")),
                ("bodyrate_x", column(rows, "so3_bodyrate_x")),
                ("bodyrate_y", column(rows, "so3_bodyrate_y")),
                ("bodyrate_z", column(rows, "so3_bodyrate_z")),
            ],
            "command value",
            "SO3 command",
        ),
    )

    if "wind_force_norm" in rows[0]:
        plot_or_warn(
            output_dir,
            "wind_force_norm.png",
            lambda plt: plot_time_series(
                plt,
                time_sec,
                [("wind_force_norm", column(rows, "wind_force_norm"))],
                "force [N]",
                "Wind force norm",
            ),
        )


def main():
    args = parse_args()
    csv_path = args.csv_path or find_latest_csv(args.default_logs_dir)
    output_dir = os.path.abspath(args.output_dir)

    rows, fieldnames = read_csv_rows(csv_path)
    missing_plot_columns = [name for name in PLOT_COLUMNS if name not in fieldnames]
    if missing_plot_columns:
        print(
            "WARNING: some plots may be incomplete because columns are missing: %s"
            % ", ".join(missing_plot_columns),
            file=sys.stderr,
        )

    metrics = compute_metrics(csv_path, rows)
    write_metrics(output_dir, metrics)
    make_plots(rows, output_dir)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (FileNotFoundError, ValueError) as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        sys.exit(1)
