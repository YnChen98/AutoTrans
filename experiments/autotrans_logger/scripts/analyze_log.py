def main():
    args = parse_args()
    csv_path = args.csv_path or find_latest_csv(args.default_logs_dir)
    output_dir = os.path.abspath(args.output_dir)

    rows, fieldnames = read_csv_rows(csv_path)
    missing_plot_columns = [name for name in PLOT_COLUMNS if name not in fieldnames]
    if missing_plot_columns:
        print(
            "WARNING: some plots may be incomplete because columns are missing: %s"
            % ", ".join(missing_plot_columns),
            file=sys.stderr,
        )

    metrics = compute_metrics(csv_path, rows, args)
    write_metrics(output_dir, metrics)
    make_plots(rows, output_dir)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (FileNotFoundError, ValueError) as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        sys.exit(1)
