def find_latest_csv(logs_dir):
    candidates = glob.glob(os.path.join(logs_dir, "autotrans_log_*.csv"))
    if not candidates:
        raise FileNotFoundError(
            "No CSV was provided and no autotrans_log_*.csv file exists in %s" % logs_dir
        )
    return max(candidates, key=os.path.getmtime)


def parse_float(value):
    if value is None:
        return math.nan
    value = str(value).strip()
    if value == "":
        return math.nan
    try:
        return float(value)
    except ValueError:
        return math.nan


def read_csv_rows(csv_path):
    if not os.path.exists(csv_path):
        raise FileNotFoundError("CSV file does not exist: %s" % csv_path)
    if os.path.getsize(csv_path) == 0:
        raise ValueError("CSV file is empty: %s" % csv_path)

    with open(csv_path, "r", newline="") as csv_file:
        reader = csv.DictReader(csv_file)
        if not reader.fieldnames:
            raise ValueError("CSV file has no header: %s" % csv_path)
        rows = list(reader)

    if not rows:
        raise ValueError("CSV file has no data rows: %s" % csv_path)

    missing_columns = [name for name in NUMERIC_COLUMNS if name not in reader.fieldnames]
    if missing_columns:
        print(
            "WARNING: missing columns: %s" % ", ".join(missing_columns),
            file=sys.stderr,
        )

    return rows, reader.fieldnames


def column(rows, name):
    return [parse_float(row.get(name)) for row in rows]


def valid_values(values):
    return [value for value in values if math.isfinite(value)]


def mean(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return sum(values) / len(values)


def percentile(values, percent):
    values = sorted(valid_values(values))
    if not values:
        return math.nan
    if len(values) == 1:
        return values[0]
    rank = (len(values) - 1) * percent / 100.0
    low_index = int(math.floor(rank))
    high_index = int(math.ceil(rank))
    if low_index == high_index:
        return values[low_index]
    weight = rank - low_index
    return values[low_index] * (1.0 - weight) + values[high_index] * weight


def max_or_nan(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return max(values)


def min_or_nan(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return min(values)


def final_or_nan(values):
    for value in reversed(values):
        if math.isfinite(value):
            return value
    return math.nan


def first_or_nan(values):
    for value in values:
        if math.isfinite(value):
            return value
    return math.nan


def final_count_or_nan(values):
    value = final_or_nan(values)
    if not math.isfinite(value):
        return math.nan
    return int(round(value))


def first_finite_time(values, time_values):
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    for value, time_value in zip(values, time_values):
        if math.isfinite(value) and math.isfinite(time_value):
            return time_value - start_time
    return math.nan


def first_below_time(values, time_values, threshold):
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    for value, time_value in zip(values, time_values):
        if math.isfinite(value) and math.isfinite(time_value) and value < threshold:
            return time_value - start_time
    return math.nan


def first_ge_time(values, time_values, threshold):
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    for value, time_value in zip(values, time_values):
        if math.isfinite(value) and math.isfinite(time_value) and value >= threshold:
            return time_value - start_time
    return math.nan


def event_values(rows, name):
    return [parse_float(row.get(name)) for row in rows]


def event_count(values):
    return sum(1 for value in values if math.isfinite(value) and value > 0.5)


def first_event_index(values):
    for index, value in enumerate(values):
        if math.isfinite(value) and value > 0.5:
            return index
    return None


def relative_time_at_index(time_values, index):
    if index is None:
        return math.nan
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    if index >= len(time_values):
        return math.nan
    time_value = time_values[index]
    if not math.isfinite(time_value):
        return math.nan
    return time_value - start_times[0]


def cumulative_count_at_or_before(count_values, time_values, event_relative_time):
    if not math.isfinite(event_relative_time):
        return math.nan
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    latest_count = math.nan
    for count_value, time_value in zip(count_values, time_values):
        if not math.isfinite(time_value):
            continue
        relative = time_value - start_time
        if relative > event_relative_time:
            break
        if math.isfinite(count_value):
            latest_count = count_value
    if not math.isfinite(latest_count):
        return math.nan
    return int(round(latest_count))


def first_event_reason(rows, index, reason_field):
    if index is None or index >= len(rows):
        return ""
    return str(rows[index].get(reason_field, "")).strip()


def happened_before(event_time, reference_time):
    if math.isfinite(event_time) and math.isfinite(reference_time):
        return event_time < reference_time
    return ""


def first_nonfinite_after_available_time(rows, fields, time_values, availability_values):
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    seen_available = False
    for row, time_value, available in zip(rows, time_values, availability_values):
        if not math.isfinite(time_value):
            continue
        if math.isfinite(available) and available > 0.5:
            seen_available = True
        if not seen_available:
            continue
        for field in fields:
            if field in row and not math.isfinite(parse_float(row.get(field))):
                return time_value - start_time
    return math.nan


def first_vector_jump_time(xs, ys, zs, time_values, threshold):
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    previous = None
    for point, time_value in zip(zip(xs, ys, zs), time_values):
        if not math.isfinite(time_value):
            continue
        if not all(math.isfinite(value) for value in point):
            continue
        if previous is not None:
            jump = math.sqrt(sum((point[index] - previous[index]) ** 2 for index in range(3)))
            if jump > threshold:
                return time_value - start_time
        previous = point
    return math.nan


def vector_error_triplets(xs_a, ys_a, zs_a, xs_b, ys_b, zs_b):
    errors = []
    for point_a, point_b in zip(zip(xs_a, ys_a, zs_a), zip(xs_b, ys_b, zs_b)):
        if all(math.isfinite(value) for value in point_a + point_b):
            errors.append(
                math.sqrt(sum((point_a[index] - point_b[index]) ** 2 for index in range(3)))
            )
        else:
            errors.append(math.nan)
    return errors


def risk_score_values(values):
    return [value if math.isfinite(value) and value >= 0.0 else math.nan for value in values]


def has_column(rows, name):
    return bool(rows) and name in rows[0]


def vector_norm_triplets(xs, ys, zs):
    norms = []
    for x_value, y_value, z_value in zip(xs, ys, zs):
        if all(math.isfinite(value) for value in (x_value, y_value, z_value)):
            norms.append(math.sqrt(x_value * x_value + y_value * y_value + z_value * z_value))
        else:
            norms.append(math.nan)
    return norms


def path_length(xs, ys, zs):
    total = 0.0
    previous = None
    for point in zip(xs, ys, zs):
        if not all(math.isfinite(value) for value in point):
            continue
        if previous is not None:
            total += math.sqrt(sum((point[i] - previous[i]) ** 2 for i in range(3)))
        previous = point
    return total if previous is not None else math.nan


def final_position(xs, ys, zs):
    for point in reversed(list(zip(xs, ys, zs))):
        if all(math.isfinite(value) for value in point):
            return point
    return None


def last_position(xs, ys, zs):
    if not xs or not ys or not zs:
        return None
    return (xs[-1], ys[-1], zs[-1])


def xy_error(position, target_x, target_y):
    if position is None:
        return math.nan
    if target_x is None or target_y is None:
        return math.nan
    return math.sqrt((position[0] - target_x) ** 2 + (position[1] - target_y) ** 2)


def z_error(position, target_z):
    if position is None or target_z is None:
        return math.nan
    return abs(position[2] - target_z)


def position_error_3d(position, target_x, target_y, target_z):
    if position is None:
        return math.nan
    if target_x is None or target_y is None or target_z is None:
        return math.nan
    return math.sqrt(
        (position[0] - target_x) ** 2
        + (position[1] - target_y) ** 2
        + (position[2] - target_z) ** 2
    )


def invalid_value_counts(rows, fields):
    counts = {}
    first_invalid_index = None
    for field in fields:
        if not has_column(rows, field):
            counts[field] = 0
            continue
        count = 0
        seen_finite_value = False
        for index, row in enumerate(rows):
            value = parse_float(row.get(field))
            if math.isfinite(value):
                seen_finite_value = True
            elif seen_finite_value:
                count += 1
                if first_invalid_index is None or index < first_invalid_index:
                    first_invalid_index = index
        counts[field] = count
    return counts, first_invalid_index


def row_has_invalid_key_state(row, fields):
    for field in fields:
        if field in row and not math.isfinite(parse_float(row.get(field))):
            return True
    return False


def compute_duration_and_rate(rows):
    ros_time = valid_values(column(rows, "ros_time"))
    wall_time = valid_values(column(rows, "wall_time"))
    times = ros_time if len(ros_time) >= 2 else wall_time
    if len(times) < 2:
        return math.nan, math.nan
    duration = times[-1] - times[0]
    if duration <= 0.0:
        return math.nan, math.nan
    return duration, (len(rows) - 1) / duration


