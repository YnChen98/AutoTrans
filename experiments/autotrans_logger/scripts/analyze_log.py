def find_latest_csv(logs_dir):
    candidates = glob.glob(os.path.join(logs_dir, "autotrans_log_*.csv"))
    if not candidates:
        raise FileNotFoundError(
            "No CSV was provided and no autotrans_log_*.csv file exists in %s" % logs_dir
        )
    return max(candidates, key=os.path.getmtime)


def parse_float(value):
    if value is None:
        return math.nan
    value = str(value).strip()
    if value == "":
        return math.nan
    try:
        return float(value)
    except ValueError:
        return math.nan


def read_csv_rows(csv_path):
    if not os.path.exists(csv_path):
        raise FileNotFoundError("CSV file does not exist: %s" % csv_path)
    if os.path.getsize(csv_path) == 0:
        raise ValueError("CSV file is empty: %s" % csv_path)

    with open(csv_path, "r", newline="") as csv_file:
        reader = csv.DictReader(csv_file)
        if not reader.fieldnames:
            raise ValueError("CSV file has no header: %s" % csv_path)
        rows = list(reader)

    if not rows:
        raise ValueError("CSV file has no data rows: %s" % csv_path)

    missing_columns = [name for name in NUMERIC_COLUMNS if name not in reader.fieldnames]
    if missing_columns:
        print(
            "WARNING: missing columns: %s" % ", ".join(missing_columns),
            file=sys.stderr,
        )

    return rows, reader.fieldnames


def column(rows, name):
    return [parse_float(row.get(name)) for row in rows]


def valid_values(values):
    return [value for value in values if math.isfinite(value)]


def mean(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return sum(values) / len(values)


def percentile(values, percent):
    values = sorted(valid_values(values))
    if not values:
        return math.nan
    if len(values) == 1:
        return values[0]
    rank = (len(values) - 1) * percent / 100.0
    low_index = int(math.floor(rank))
    high_index = int(math.ceil(rank))
    if low_index == high_index:
        return values[low_index]
    weight = rank - low_index
    return values[low_index] * (1.0 - weight) + values[high_index] * weight


def max_or_nan(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return max(values)


def min_or_nan(values):
    values = valid_values(values)
    if not values:
        return math.nan
    return min(values)


def final_or_nan(values):
    for value in reversed(values):
        if math.isfinite(value):
            return value
    return math.nan


def first_finite_time(values, time_values):
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    for value, time_value in zip(values, time_values):
        if math.isfinite(value) and math.isfinite(time_value):
            return time_value - start_time
    return math.nan


def first_below_time(values, time_values, threshold):
    start_times = valid_values(time_values)
    if not start_times:
        return math.nan
    start_time = start_times[0]
    for value, time_value in zip(values, time_values):
        if math.isfinite(value) and math.isfinite(time_value) and value < threshold:
            return time_value - start_time
    return math.nan


def risk_score_values(values):
    return [value if math.isfinite(value) and value >= 0.0 else math.nan for value in values]


def has_column(rows, name):
    return bool(rows) and name in rows[0]


def vector_norm_triplets(xs, ys, zs):
    norms = []
    for x_value, y_value, z_value in zip(xs, ys, zs):
        if all(math.isfinite(value) for value in (x_value, y_value, z_value)):
            norms.append(math.sqrt(x_value * x_value + y_value * y_value + z_value * z_value))
        else:
            norms.append(math.nan)
    return norms


def path_length(xs, ys, zs):
    total = 0.0
    previous = None
    for point in zip(xs, ys, zs):
        if not all(math.isfinite(value) for value in point):
            continue
        if previous is not None:
            total += math.sqrt(sum((point[i] - previous[i]) ** 2 for i in range(3)))
        previous = point
    return total if previous is not None else math.nan


def final_position(xs, ys, zs):
    for point in reversed(list(zip(xs, ys, zs))):
        if all(math.isfinite(value) for value in point):
            return point
    return None


def last_position(xs, ys, zs):
    if not xs or not ys or not zs:
        return None
    return (xs[-1], ys[-1], zs[-1])


def xy_error(position, target_x, target_y):
    if position is None:
        return math.nan
    if target_x is None or target_y is None:
        return math.nan
    return math.sqrt((position[0] - target_x) ** 2 + (position[1] - target_y) ** 2)


def z_error(position, target_z):
    if position is None or target_z is None:
        return math.nan
    return abs(position[2] - target_z)


def position_error_3d(position, target_x, target_y, target_z):
    if position is None:
        return math.nan
    if target_x is None or target_y is None or target_z is None:
        return math.nan
    return math.sqrt(
        (position[0] - target_x) ** 2
        + (position[1] - target_y) ** 2
        + (position[2] - target_z) ** 2
    )


def invalid_value_counts(rows, fields):
    counts = {}
    first_invalid_index = None
    for field in fields:
        if not has_column(rows, field):
            counts[field] = 0
            continue
        count = 0
        seen_finite_value = False
        for index, row in enumerate(rows):
            value = parse_float(row.get(field))
            if math.isfinite(value):
                seen_finite_value = True
            elif seen_finite_value:
                count += 1
                if first_invalid_index is None or index < first_invalid_index:
                    first_invalid_index = index
        counts[field] = count
    return counts, first_invalid_index


def row_has_invalid_key_state(row, fields):
    for field in fields:
        if field in row and not math.isfinite(parse_float(row.get(field))):
            return True
    return False


def compute_duration_and_rate(rows):
    ros_time = valid_values(column(rows, "ros_time"))
    wall_time = valid_values(column(rows, "wall_time"))
    times = ros_time if len(ros_time) >= 2 else wall_time
    if len(times) < 2:
        return math.nan, math.nan
    duration = times[-1] - times[0]
    if duration <= 0.0:
        return math.nan, math.nan
    return duration, (len(rows) - 1) / duration


def compute_metrics(csv_path, rows, args):
    uav_pos_x = column(rows, "uav_pos_x")
    uav_pos_y = column(rows, "uav_pos_y")
    uav_pos_z = column(rows, "uav_pos_z")
    uav_vel_x = column(rows, "uav_vel_x")
    uav_vel_y = column(rows, "uav_vel_y")
    uav_vel_z = column(rows, "uav_vel_z")

    payload_pos_x = column(rows, "payload_pos_x")
    payload_pos_y = column(rows, "payload_pos_y")
    payload_pos_z = column(rows, "payload_pos_z")
    payload_vel_x = column(rows, "payload_vel_x")
    payload_vel_y = column(rows, "payload_vel_y")
    payload_vel_z = column(rows, "payload_vel_z")

    uav_speed = vector_norm_triplets(uav_vel_x, uav_vel_y, uav_vel_z)
    payload_speed = vector_norm_triplets(payload_vel_x, payload_vel_y, payload_vel_z)
    swing_angle = column(rows, "swing_angle_deg")
    has_trajectory = column(rows, "has_trajectory")
    valid_has_trajectory = valid_values(has_trajectory)
    wind_force_norm = column(rows, "wind_force_norm") if has_column(rows, "wind_force_norm") else []
    command_speed_scale = column(rows, "command_speed_scale") if has_column(rows, "command_speed_scale") else []
    command_acceleration_scale = (
        column(rows, "command_acceleration_scale")
        if has_column(rows, "command_acceleration_scale")
        else []
    )
    command_risk_score_3s = (
        risk_score_values(column(rows, "command_risk_score_3s"))
        if has_column(rows, "command_risk_score_3s")
        else []
    )
    command_risk_score_5s = (
        risk_score_values(column(rows, "command_risk_score_5s"))
        if has_column(rows, "command_risk_score_5s")
        else []
    )
    command_risk_scale_selected = (
        column(rows, "command_risk_scale_selected")
        if has_column(rows, "command_risk_scale_selected")
        else []
    )

    duration_sec, effective_log_rate_hz = compute_duration_and_rate(rows)
    final_valid_uav_position = final_position(uav_pos_x, uav_pos_y, uav_pos_z)
    final_valid_payload_position = final_position(payload_pos_x, payload_pos_y, payload_pos_z)
    last_row_uav_position = last_position(uav_pos_x, uav_pos_y, uav_pos_z)
    last_row_payload_position = last_position(payload_pos_x, payload_pos_y, payload_pos_z)
    nan_counts, first_nan_index = invalid_value_counts(rows, KEY_STATE_FIELDS)
    nan_count_total = sum(nan_counts.values())
    has_nan_state = nan_count_total > 0
    final_row_has_nan = row_has_invalid_key_state(rows[-1], KEY_STATE_FIELDS)
    ros_times = column(rows, "ros_time")
    valid_ros_times = valid_values(ros_times)
    first_ros_time = valid_ros_times[0] if valid_ros_times else math.nan
    first_nan_ros_time = ""
    first_nan_time = ""
    if first_nan_index is not None:
        first_nan_ros_value = ros_times[first_nan_index] if first_nan_index < len(ros_times) else math.nan
        if math.isfinite(first_nan_ros_value):
            first_nan_ros_time = first_nan_ros_value
            if math.isfinite(first_ros_time):
                first_nan_time = first_nan_ros_value - first_ros_time

    max_uav_speed = max_or_nan(uav_speed)
    max_payload_speed = max_or_nan(payload_speed)
    max_swing_angle_deg = max_or_nan(swing_angle)
    has_target_xy = args.target_x is not None and args.target_y is not None
    final_uav_xy_error = xy_error(final_valid_uav_position, args.target_x, args.target_y)
    final_payload_xy_error = xy_error(final_valid_payload_position, args.target_x, args.target_y)
    final_uav_z_error = z_error(final_valid_uav_position, args.target_z)
    final_payload_z_error = z_error(final_valid_payload_position, args.payload_target_z)
    final_uav_position_error_3d = position_error_3d(
        final_valid_uav_position,
        args.target_x,
        args.target_y,
        args.target_z,
    )
    final_payload_position_error_3d = position_error_3d(
        final_valid_payload_position,
        args.target_x,
        args.target_y,
        args.payload_target_z,
    )
    target_xy_failure = (
        has_target_xy
        and math.isfinite(final_uav_xy_error)
        and final_uav_xy_error > args.target_xy_tolerance
    )

    unreasonable_final_altitude = (
        final_valid_uav_position is not None
        and final_valid_payload_position is not None
        and (
            final_valid_uav_position[2] < MIN_REASONABLE_UAV_Z
            or final_valid_payload_position[2] < MIN_REASONABLE_PAYLOAD_Z
        )
    )
    # This is an experiment validity heuristic, not a physics proof.
    valid_run_suggested = not (
        has_nan_state
        or final_row_has_nan
        or final_valid_uav_position is None
        or final_valid_payload_position is None
        or (math.isfinite(max_uav_speed) and max_uav_speed > MAX_REASONABLE_SPEED_MPS)
        or (math.isfinite(max_payload_speed) and max_payload_speed > MAX_REASONABLE_SPEED_MPS)
        or (math.isfinite(max_swing_angle_deg) and max_swing_angle_deg > MAX_REASONABLE_SWING_DEG)
        or unreasonable_final_altitude
        or target_xy_failure
    )

    if valid_has_trajectory and max(valid_has_trajectory) <= 0.0:
        print("WARNING: no valid trajectory data detected in has_trajectory.", file=sys.stderr)
    elif not valid_has_trajectory:
        print("WARNING: has_trajectory has no valid numeric data.", file=sys.stderr)

    metrics = {
        "csv_path": os.path.abspath(csv_path),
        "sample_count": len(rows),
        "duration_sec": duration_sec,
        "effective_log_rate_hz": effective_log_rate_hz,
        "has_nan_state": has_nan_state,
        "first_nan_time": first_nan_time,
        "first_nan_ros_time": first_nan_ros_time,
        "final_row_has_nan": final_row_has_nan,
        "valid_run_suggested": valid_run_suggested,
        "nan_count_total": nan_count_total,
        "has_trajectory_ratio": mean([1.0 if value > 0.5 else 0.0 for value in valid_has_trajectory]),
        "mean_swing_angle_deg": mean(swing_angle),
        "max_swing_angle_deg": max_swing_angle_deg,
        "p95_swing_angle_deg": percentile(swing_angle, 95.0),
        "max_uav_speed": max_uav_speed,
        "mean_uav_speed": mean(uav_speed),
        "max_payload_speed": max_payload_speed,
        "mean_payload_speed": mean(payload_speed),
        "uav_path_length": path_length(uav_pos_x, uav_pos_y, uav_pos_z),
        "payload_path_length": path_length(payload_pos_x, payload_pos_y, payload_pos_z),
        "final_uav_position": final_valid_uav_position,
        "final_payload_position": final_valid_payload_position,
        "final_valid_uav_position": final_valid_uav_position,
        "final_valid_payload_position": final_valid_payload_position,
        "last_row_uav_position": last_row_uav_position,
        "last_row_payload_position": last_row_payload_position,
    }
    for field in KEY_STATE_FIELDS:
        metrics["nan_count_%s" % field] = nan_counts[field]

    if wind_force_norm:
        metrics["mean_wind_force_norm"] = mean(wind_force_norm)
        metrics["max_wind_force_norm"] = max_or_nan(wind_force_norm)

    if has_target_xy:
        metrics["target_xy_tolerance"] = args.target_xy_tolerance
        metrics["final_uav_xy_error"] = final_uav_xy_error
        metrics["final_payload_xy_error"] = final_payload_xy_error

    if args.target_z is not None:
        metrics["final_uav_z_error"] = final_uav_z_error
        if has_target_xy:
            metrics["final_uav_position_error_3d"] = final_uav_position_error_3d

    if args.payload_target_z is not None:
        metrics["final_payload_z_error"] = final_payload_z_error
        if has_target_xy:
            metrics["final_payload_position_error_3d"] = final_payload_position_error_3d

    if command_speed_scale:
        if valid_values(command_speed_scale):
            metrics["mean_command_speed_scale"] = mean(command_speed_scale)
            metrics["min_command_speed_scale"] = min_or_nan(command_speed_scale)
            metrics["max_command_speed_scale"] = max_or_nan(command_speed_scale)
            metrics["final_command_speed_scale"] = final_or_nan(command_speed_scale)
            metrics["first_command_scale_below_0p85_time"] = first_below_time(
                command_speed_scale, ros_times, 0.85
            )
            metrics["first_command_scale_below_0p75_time"] = first_below_time(
                command_speed_scale, ros_times, 0.75
            )
        else:
            print("WARNING: command_speed_scale has no finite numeric data.", file=sys.stderr)

    if command_acceleration_scale:
        if valid_values(command_acceleration_scale):
            metrics["mean_command_acceleration_scale"] = mean(command_acceleration_scale)
            metrics["min_command_acceleration_scale"] = min_or_nan(command_acceleration_scale)
            metrics["max_command_acceleration_scale"] = max_or_nan(command_acceleration_scale)
            metrics["final_command_acceleration_scale"] = final_or_nan(command_acceleration_scale)
        else:
            print("WARNING: command_acceleration_scale has no finite numeric data.", file=sys.stderr)

    if command_risk_score_3s:
        if valid_values(command_risk_score_3s):
            metrics["mean_command_risk_score_3s"] = mean(command_risk_score_3s)
            metrics["max_command_risk_score_3s"] = max_or_nan(command_risk_score_3s)
            metrics["final_command_risk_score_3s"] = final_or_nan(command_risk_score_3s)
            metrics["first_finite_command_risk_score_3s_time"] = first_finite_time(
                command_risk_score_3s, ros_times
            )
        else:
            print("WARNING: command_risk_score_3s has no finite non-negative data.", file=sys.stderr)

    if command_risk_score_5s:
        if valid_values(command_risk_score_5s):
            metrics["mean_command_risk_score_5s"] = mean(command_risk_score_5s)
            metrics["max_command_risk_score_5s"] = max_or_nan(command_risk_score_5s)
            metrics["final_command_risk_score_5s"] = final_or_nan(command_risk_score_5s)
            metrics["first_finite_command_risk_score_5s_time"] = first_finite_time(
                command_risk_score_5s, ros_times
            )
        else:
            print("WARNING: command_risk_score_5s has no finite non-negative data.", file=sys.stderr)

    if command_risk_scale_selected:
        if valid_values(command_risk_scale_selected):
            metrics["mean_command_risk_scale_selected"] = mean(command_risk_scale_selected)
            metrics["min_command_risk_scale_selected"] = min_or_nan(command_risk_scale_selected)
            metrics["max_command_risk_scale_selected"] = max_or_nan(command_risk_scale_selected)
            metrics["final_command_risk_scale_selected"] = final_or_nan(command_risk_scale_selected)
        else:
            print("WARNING: command_risk_scale_selected has no finite numeric data.", file=sys.stderr)

    return metrics


def format_value(value):
    if value == "":
        return ""
    if value is None:
        return "nan"
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, tuple):
        return "(%.6f, %.6f, %.6f)" % value
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if math.isfinite(value):
            return "%.6f" % value
        return "nan"
    return str(value)


def write_metrics(output_dir, metrics):
    os.makedirs(output_dir, exist_ok=True)
    lines = ["%s: %s" % (key, format_value(value)) for key, value in metrics.items()]
    text = "\n".join(lines) + "\n"
    print(text, end="")
    summary_path = os.path.join(output_dir, "metrics_summary.txt")
    with open(summary_path, "w") as summary_file:
        summary_file.write(text)
    print("metrics_summary_path: %s" % os.path.abspath(summary_path))


def relative_time(rows):
    times = column(rows, "ros_time")
    valid_times = valid_values(times)
    if not valid_times:
        return [math.nan for _ in rows]
    start_time = valid_times[0]
    return [value - start_time if math.isfinite(value) else math.nan for value in times]


def finite_xy(xs, ys):
    out_x = []
    out_y = []
    for x_value, y_value in zip(xs, ys):
        if math.isfinite(x_value) and math.isfinite(y_value):
            out_x.append(x_value)
            out_y.append(y_value)
    return out_x, out_y


def plot_or_warn(output_dir, filename, plot_func):
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("WARNING: matplotlib is not available; plots were not generated.", file=sys.stderr)
        return False

    path = os.path.join(output_dir, filename)
    try:
        fig = plt.figure()
        plot_func(plt)
        fig.tight_layout()
        fig.savefig(path, dpi=150)
        plt.close(fig)
        return True
    except Exception as exc:
        plt.close("all")
        print("WARNING: failed to generate %s: %s" % (filename, exc), file=sys.stderr)
        return False


def plot_time_series(plt, time_sec, series, ylabel, title):
    plotted = False
    for label, values in series:
        xs = []
        ys = []
        for time_value, value in zip(time_sec, values):
            if math.isfinite(time_value) and math.isfinite(value):
                xs.append(time_value)
                ys.append(value)
        if xs:
            plt.plot(xs, ys, label=label)
            plotted = True
    if not plotted:
        raise ValueError("no finite data")
    plt.xlabel("time [s]")
    plt.ylabel(ylabel)
    plt.title(title)
    plt.grid(True)
    if len(series) > 1:
        plt.legend()


