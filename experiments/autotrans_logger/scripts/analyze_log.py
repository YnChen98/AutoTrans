def format_value(value):
    if value == "":
        return ""
    if value is None:
        return "nan"
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, tuple):
        return "(%.6f, %.6f, %.6f)" % value
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if math.isfinite(value):
            return "%.6f" % value
        return "nan"
    return str(value)


def write_metrics(output_dir, metrics):
    os.makedirs(output_dir, exist_ok=True)
    lines = ["%s: %s" % (key, format_value(value)) for key, value in metrics.items()]
    text = "\n".join(lines) + "\n"
    print(text, end="")
    summary_path = os.path.join(output_dir, "metrics_summary.txt")
    with open(summary_path, "w") as summary_file:
        summary_file.write(text)
    print("metrics_summary_path: %s" % os.path.abspath(summary_path))


def relative_time(rows):
    times = column(rows, "ros_time")
    valid_times = valid_values(times)
    if not valid_times:
        return [math.nan for _ in rows]
    start_time = valid_times[0]
    return [value - start_time if math.isfinite(value) else math.nan for value in times]


def finite_xy(xs, ys):
    out_x = []
    out_y = []
    for x_value, y_value in zip(xs, ys):
        if math.isfinite(x_value) and math.isfinite(y_value):
            out_x.append(x_value)
            out_y.append(y_value)
    return out_x, out_y


def plot_or_warn(output_dir, filename, plot_func):
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("WARNING: matplotlib is not available; plots were not generated.", file=sys.stderr)
        return False

    path = os.path.join(output_dir, filename)
    try:
        fig = plt.figure()
        plot_func(plt)
        fig.tight_layout()
        fig.savefig(path, dpi=150)
        plt.close(fig)
        return True
    except Exception as exc:
        plt.close("all")
        print("WARNING: failed to generate %s: %s" % (filename, exc), file=sys.stderr)
        return False


def plot_time_series(plt, time_sec, series, ylabel, title):
    plotted = False
    for label, values in series:
        xs = []
        ys = []
        for time_value, value in zip(time_sec, values):
            if math.isfinite(time_value) and math.isfinite(value):
                xs.append(time_value)
                ys.append(value)
        if xs:
            plt.plot(xs, ys, label=label)
            plotted = True
    if not plotted:
        raise ValueError("no finite data")
    plt.xlabel("time [s]")
    plt.ylabel(ylabel)
    plt.title(title)
    plt.grid(True)
    if len(series) > 1:
        plt.legend()


